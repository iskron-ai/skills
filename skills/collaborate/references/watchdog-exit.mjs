#!/usr/bin/env node
// node watchdog-exit.mjs <адрес-сокета>   — сторож выхода-на-кадре, без зависимостей, Node 22+.
// Адрес — секрет: где командные строки читаемы (ps, история шелла), передай его
// переменной окружения ISKRON_CHANNEL_SOCKET и запускай без аргумента.
//
// Для харнесов БЕЗ встроенного наблюдателя сокета. Там вывод фоновой задачи
// читается только по запросу, и единственное, что харнес превращает в
// прерывание, — конец процесса. Поэтому этот сторож не печатает кадр в надежде,
// что кто-то заглянет: он печатает его и ВЫХОДИТ нулём на первом рабочем кадре.
// Делатель просыпается концом процесса — и ПЕРВЫМ ходом запускает сторожа снова,
// до того как возьмётся за кадр. Перевзвод есть шаг протокола, не памятка, и он
// именно первый: взведённый после работы опаздывает ровно на её длину, а такт,
// не доживший до конца (кончился контекст, вмешался человек, упала работа), не
// взводит его никогда — стояние остаётся глухим с полной очередью, пока
// отправители видят accepted. Двух слушателей это не плодит: прежний вышел ровно
// тем, что доставил кадр. Где кадр идёт через мост — мост перевзводится так же.
//
// Где встроенный наблюдатель есть (в Claude Code — Monitor со сторожем как
// command и persistent: true), нужен не этот файл, а watchdog.mjs рядом.
//
// Три правила делают паттерн безопасным, и каждое здесь — строчка кода:
//   служебные кадры (hello, пинги) — не выход: служба говорит первой, и наивный
//     слушатель ушёл бы в вахту на её приветствии;
//   мёртвый токен — выход ГРОМКИЙ, ненулевой: иначе протухший грант неотличим
//     от пустого инбокса;
//   выкатка и сетевой обрыв — не выход вовсе: их переоткрывают, иначе делателя
//     будят на событии, которое его не касается.
//
// Боевые заметки — в channel.md рядом с этим файлом: почему попытка считается
// от конструкции (никогда от onopen), почему пауза не растёт и почему три
// быстрых обрыва спрашивают /version, прежде чем винить токен.
// Он же несёт строку занятости НАРУЖУ — вторая половина файла. Здесь она вдобавок
// самопочинна: сторож живёт от кадра до кадра, а перевзведённый публикует текущее
// содержимое файла заново, ничего не помня о прошлой жизни.
import { readFileSync, writeSync } from "node:fs";

const url = process.argv[2] || process.env.ISKRON_CHANNEL_SOCKET;
if (!url) {
  writeSync(2, "нужен адрес сокета: node watchdog-exit.mjs <wss://…> или ISKRON_CHANNEL_SOCKET\n");
  process.exit(2);
}
const version = new URL(url).origin.replace("wss:", "https:") + "/api/version";
let fastDrops = 0;

// Синхронная запись, а не process.stdout.write: в трубу тот пишет асинхронно, и
// выход следом теряет ровно то, ради чего файл существует, — сам кадр.
const wake = (s) => writeSync(1, s + "\n"); // делателю: то, что его будит
const note = (s) => writeSync(2, s + "\n"); // в лог: то, что будить не должно
const serviceUp = () => fetch(version, { signal: AbortSignal.timeout(5000) })
  .then((r) => (r.ok ? r.json() : null)).catch(() => null);

function open() {
  const startedAt = Date.now();           // от конструкции, НЕ в onopen — см. channel.md
  const ws = new WebSocket(url);

  ws.addEventListener("message", (e) => {
    const raw = typeof e.data === "string" ? e.data : null;
    let type = null;
    try { type = JSON.parse(raw)?.type; } catch { /* не JSON — служебным и останется */ }
    if (type !== "message") return note(`кадр ${type ?? "не разобран"} — не повод будить`);
    wake(raw);
    process.exit(0);                      // конец процесса И ЕСТЬ доставка
  });

  ws.addEventListener("error", () => {}); // закрытие придёт следом в любом случае
  ws.addEventListener("close", async (e) => {
    if ([4000, 4001, 4002].includes(e.code)) {
      note(`ДЕЛАТЕЛЬ: закрытие ${e.code} — токен мёртв, зови connect (на 4001 — mint)`);
      process.exit(1);                    // громко: мёртвый токен не смеет выглядеть пустым инбоксом
    }
    fastDrops = Date.now() - startedAt < 5000 ? fastDrops + 1 : 0;
    if (fastDrops >= 3) {
      const up = await serviceUp();
      if (up) {
        note(`ДЕЛАТЕЛЬ: обрывы, а служба отвечает (${up.version}) — спроси о токене`);
        process.exit(1);
      }
      note("служба не отвечает — идёт раскатка, держу тот же токен");
      fastDrops = 1;                      // простой не должен перерасти в вопрос о токене
    }
    setTimeout(open, e.code === 4003 ? 3000 : 2000);
  });
}
open();

// ── Вторая половина: слово делателя наружу ──────────────────────────────────
// Делатель пишет ТЕКСТ строки занятости в файл, публикует сторож: слушающий секрет
// у него, не у рабочей сессии. Разбор — в channel.md, «Когда сокет держит сторож».
// Без переменной половина не включается вовсе.
const sayFile = process.env.ISKRON_CHANNEL_SAY;
// Выданный рядом с сокетом адрес — первый; вывод из формы — фолбэк, потому что
// сторожу вручают сокет, а не ответ connect целиком, а форма адресов дрейфует.
const statusUrl = process.env.ISKRON_CHANNEL_STATUS
  || url.replace(/^wss:/, "https:").replace(/^ws:/, "http:").replace("/channel/ws/", "/channel/status/");
let said = null, complained = null;

// Опрос, а не наблюдение за файлом: файла может ещё не быть, а наблюдатель за
// несуществующим путём бросает; пересоздание целиком опрос тоже переживает.
async function say() {
  let text;
  try { text = readFileSync(sayFile, "utf8").trim(); } catch { return; } // ещё не написали — не о чем говорить
  if (text === said) return;              // публикуют смену занятия, а не такт
  const res = await fetch(statusUrl, {
    method: "POST", headers: { "content-type": "application/json" },
    body: JSON.stringify({ text }), signal: AbortSignal.timeout(5000),
  }).catch(() => null);
  if (res?.ok) { said = text; complained = null; return; } // пустая строка — СЛОВО: ею занятость снимают
  if (complained !== text) {              // жалоба раз на текст, а не раз в секунду
    complained = text;                    // в лог, НЕ в stdout: там будит только кадр
    note(`ДЕЛАТЕЛЬ: строку занятости не приняли (${res ? res.status : "нет ответа"}) — см. channel.md`);
  }
  if (res && res.status >= 400 && res.status < 500) said = text; // отказ по самой строке: повтор той же ничего не изменит
}
if (sayFile) setInterval(say, 1000).unref(); // таймер не смеет держать процесс, чья работа — выйти на кадре
