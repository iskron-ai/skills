// Дверь Искрона в сессию pi — ОДНО расширение, две независимые половины.
//
//   • тулы     — расширение поднимает мост дочерним процессом и регистрирует
//                каждый тул сервера под его собственным именем (tools.ts);
//   • канал    — кадры стояния, которое держит мост, входят в идущий ход
//                (channel.ts).
//
// Сокет стояния держит мост — дочерний процесс этой же сессии: он берёт адрес
// из ответа connect, переоткрывает, различает мёртвый токен, публикует
// занятость. Секрет не покидает моста; расширение видит только уведомления
// MCP с кадрами и превращает их в то, чего у моста нет, — ход агента.
//
// Почему один файл на выходе. Каталог `extensions/` — конвенционный: pi считает
// отдельным расширением КАЖДЫЙ .ts/.js в нём (обход на один уровень, без
// рекурсии). Значит «одно расширение» буквально значит «один файл»; всякий
// сосед рядом стал бы вторым расширением. Исходник при этом не обязан быть
// одним файлом: эти модули собираются esbuild-ом в extensions/iskron.js.
//
// Фабрика не поднимает ничего живого: pi зовёт её и в вызовах, где сессии не
// будет вовсе. Мост и таймеры — только от session_start до session_shutdown,
// и снятие идемпотентно.
import type { ExtensionAPI } from "@earendil-works/pi-coding-agent";

import { setupChannel } from "./channel.ts";
import { setupBridge } from "./tools.ts";

export default function (pi: ExtensionAPI) {
  // Половины ставятся порознь и каждая под своим try: сорвавшаяся регистрация
  // одной не должна унести с собой другую — и не должна унести сессию.
  const broken: string[] = [];

  // Сообщаем о сорвавшейся постановке в самой сессии, а не в лог: в rpc-режиме
  // stdout занят протоколом, и напечатанное туда было бы порчей, а не словом.
  pi.on("session_start", async (_event, ctx) => {
    if (!broken.length || !ctx.hasUI) return;
    ctx.ui.notify(`Искрон: не встало — ${broken.join("; ")}`, "error");
  });

  // Канал ставится первым: он отдаёт дверь, которой половина «тулы» подаёт ему
  // уведомления моста. Сорвись он — дверь остаётся заглушкой, и половина «тулы»
  // встаёт как ни в чём не бывало; обратное тоже верно.
  let onChannel: (params: unknown) => void = () => {};
  try {
    onChannel = setupChannel(pi);
  } catch (e) {
    broken.push(`канал: ${e instanceof Error ? e.message : String(e)}`);
  }
  try {
    setupBridge(pi, (params) => onChannel(params));
  } catch (e) {
    broken.push(`тулы: ${e instanceof Error ? e.message : String(e)}`);
  }
}
