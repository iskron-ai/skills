// Последняя работа агента — точка для хартбита места (граф nks-dev: #6510; сам
// хартбит — отдельным шагом): миг последнего слова харнеса этой сессии — всякий
// JSON-RPC от него, iskron/usage тоже. На сессию (shared/scope.ts): у демона
// машины — своя у каждой сессии, и публиковать её он будет за каждое место.
import { scoped } from "../shared/scope.ts";

const W = scoped(() => ({ at: 0 }));

/** Харнес сказал слово (session.ts, на каждую строку входа, кроме ходов самого тонкого моста). */
export function noteAgentWork(at = Date.now()): void {
  W.at = at;
}

/** Миг последней работы агента этой сессии (мс эпохи); 0 — харнес ещё не говорил. */
export const lastAgentWork = (): number => W.at;
