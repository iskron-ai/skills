// Строка запуска с делом (граф @nks/nks-dev, узлы #6078, #6809): «start <граф> <роль>
// <дело №N> [от <место>]» или «start <graph> <role> <case №N> [from <seat>]» — на любом
// языке сессии. Разбор позиционный (роль сама пишется «#N»): граф, роль, затем дело —
// «дело №N», «дело #N», «case #N» или голое «№N»/«#N». Строка запуска — первая строка
// текста, которая с неё начинается: OpenCode ставит перед промптом субагента свою строку.
// Группы: 1 — граф, 2 — роль, 3 — номер дела, 4 — место запустившего.
export const LAUNCH_LINE =
  /^[ \t]*start\s+(\S+)\s+(\S+)\s+(?:(?:дело|case)\s+)?[№#]\s?(\d+)(?:[ \t]+(?:от|from)[ \t]+(@\S+))?(?=\s|$)/imu;
